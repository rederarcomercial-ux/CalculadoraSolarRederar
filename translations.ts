export type LanguageCode = "es" | "pt" | "en" | "fr";

export function getCountryLanguage(countryName?: string): LanguageCode {
  const name = (countryName || "Argentina").toLowerCase().trim();

  // 1. Portuguese speaking countries
  if (
    name.includes("brasil") ||
    name.includes("brazil") ||
    name.includes("portugal") ||
    name.includes("angola") ||
    name.includes("moçambique") ||
    name.includes("mozambique") ||
    name.includes("cabo verde") ||
    name.includes("cape verde") ||
    name.includes("guiné-bissau") ||
    name.includes("guinea-bissau") ||
    name.includes("são tomé") ||
    name.includes("sao tome") ||
    name.includes("timor")
  ) {
    return "pt";
  }

  // 2. French speaking countries
  if (
    name.includes("haití") ||
    name.includes("haiti") ||
    name.includes("guayana francesa") ||
    name.includes("french guiana") ||
    name.includes("guyane") ||
    name.includes("guadalupe") ||
    name.includes("guadeloupe") ||
    name.includes("martinica") ||
    name.includes("martinique") ||
    name.includes("saint-martin") ||
    name.includes("saint martin") ||
    name.includes("saint-barthélemy") ||
    name.includes("francia") ||
    name.includes("france") ||
    name.includes("french") ||
    name.includes("français") ||
    name.includes("francés") ||
    name.includes("bélgica") ||
    name.includes("belgium") ||
    name.includes("suiza") ||
    name.includes("switzerland") ||
    name.includes("senegal") ||
    name.includes("mali") ||
    name.includes("mónaco") ||
    name.includes("monaco") ||
    name.includes("camerún") ||
    name.includes("cameroon") ||
    name.includes("congo") ||
    name.includes("cote d'ivoire") ||
    name.includes("costa de marfil") ||
    name.includes("madagascar")
  ) {
    return "fr";
  }

  // 3. Spanish speaking countries
  if (
    name.includes("argentina") ||
    name.includes("chile") ||
    name.includes("colombia") ||
    name.includes("españa") ||
    name.includes("spain") ||
    name.includes("méxico") ||
    name.includes("mexico") ||
    name.includes("perú") ||
    name.includes("peru") ||
    name.includes("uruguay") ||
    name.includes("paraguay") ||
    name.includes("bolivia") ||
    name.includes("costa rica") ||
    name.includes("cuba") ||
    name.includes("ecuador") ||
    name.includes("el salvador") ||
    name.includes("guatemala") ||
    name.includes("honduras") ||
    name.includes("nicaragua") ||
    name.includes("panamá") ||
    name.includes("panama") ||
    name.includes("puerto rico") ||
    name.includes("república dominicana") ||
    name.includes("dominican republic") ||
    name.includes("venezuela") ||
    name.includes("guinea ecuatorial") ||
    name.includes("equatorial guinea")
  ) {
    return "es";
  }

  // 4. Default for all other international countries (Curazao, Aruba, Sint Maarten, USA, Canada, UK, etc.)
  return "en";
}

