export function getTranslation(key: string, countryName?: string): string {
  const lang = getCountryLanguage(countryName);
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.es;
  return dict[key] || TRANSLATIONS.es[key] || key;
}

export function getAppliancePresetName(id: string, countryName?: string): string {
  const lang = getCountryLanguage(countryName);
  const dict = APPLIANCE_PRESET_TRANSLATIONS[lang] || APPLIANCE_PRESET_TRANSLATIONS.es;
  return dict[id] || dict.preset_all;
}

export function translateApplianceName(name: string, countryName?: string): string {
  const lang = getCountryLanguage(countryName);
  const presetsDict = APPLIANCE_PRESET_TRANSLATIONS.es;
  const foundEntry = Object.entries(presetsDict).find(([_, val]) => val.toLowerCase() === name.toLowerCase());
  if (foundEntry) {
    const key = foundEntry[0];
    const targetDict = APPLIANCE_PRESET_TRANSLATIONS[lang] || APPLIANCE_PRESET_TRANSLATIONS.es;
    return targetDict[key] || name;
  }
  return name;
}
